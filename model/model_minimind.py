            # ------------------------------------------------------------------------------
            # 缩放操作：score ← score / √d_k

            # 理论依据：方差归一化原理
            #   • 原方差：Var(QK^T) = d_k
            #   • 缩放后：Var(scaled) = d_k / (√d_k)^2 = 1
            #   • 新值域：±3σ → 约±3 (相比原来的±3√d_k)


