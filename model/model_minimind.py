            # 【关键技术点说明】
            # ───────────────────────────────────────────────────────────────────────────────
            # 1. RMSNorm 归一化 (Root Mean Square Normalization)
            #    • 与 LayerNorm 对比:
            #      ┌───────────────┬─────────────────────────────┐
            #      │ LayerNorm     │ 计算: (x-μ)/σ × γ + β       │
            #      │ (标准方法)    │  • 减去均值 μ               │
            #      │               │  • 除以标准差 σ             │
            #      └───────────────┴─────────────────────────────┘
            #      ┌───────────────┬─────────────────────────────┐
            #      │ RMSNorm       │ 计算: x/RMS × γ             │
            #      │ (当前方法)    │  • 仅计算均方根 RMS=√(Σx²/n)│
            #      │               │  • 无需均值中心化            │
            #      │               │  • 可学习权重 γ (标量/向量)  │
            #      └───────────────┴─────────────────────────────┘
            #    • 优势: 
            #      - 计算量减少约 25% (省去均值计算)
            #      - 实践中表现与 LayerNorm 相当或更优
            #      - 更适合大模型训练

