            #    • 作用:
            #      - 建立跨层直连通路
            #      - 缓解深层网络梯度消失
            #      - 保留原始输入信息

            # 3. FFN with SwiGLU
            #    • 结构: 
            #      ┌────────────┐    ┌────────────┐
            #      │ 线性变换   │───▶│ Swish激活  │───┐
            #      │ W1 (扩展)  │    │            │   │
            #      └────────────┘    └────────────┘   │
            #                                         ▼
            #                           ┌──────────────────────────┐
