            # ------------------------------------------------------------------------------
            # 通过Jacobian矩阵分析softmax反向传播特性

            # 导数公式推导：
            #   ∂p_i/∂z_j = p_i * (I(i=j) - p_j)
            
            # 梯度分量分类计算：
            #   • 自导数项 (i=j):
            #     - 饱和时：p_max≈1 → p_max*(1-p_max)≈0
            #     - 例：p=[0,0,0.001,0.999]
            #       ∂p4/∂z4 = 0.999*(1-0.999) ≈ 0.001
            
            #   • 交叉导数项 (i≠j):
            #     - 非最大项：∂p_nonmax/∂z_max = -p_nonmax * p_max ≈0
            #     - 最大项交叉项：p_max * p_j ≈0 (j≠max_idx)

