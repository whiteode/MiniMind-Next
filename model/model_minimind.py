            scoring_func: str = 'softmax',          # 门控网络 (Gate) 计算路由权重的评分函数，默认为 softmax
            # 含义：词是怎么知道自己该去哪个专家的？模型里有一个极小的神经网络叫 Gate（门控网络/路由器），就像医院的分诊台护士。

