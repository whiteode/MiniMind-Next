            #   ┌─────────────┬─────────────┐
            #   │ 前半部分    │ 后半部分    │
            #   ├─────────────┼─────────────┤
            #   │ [q1, q2]    │ [q3, q4]    │
            #   └─────────────┴─────────────┘
