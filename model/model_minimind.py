            # ==============================================================================
            # 阶段一：QK^T 数值爆炸的成因分析
            # ------------------------------------------------------------------------------
            # 核心发现：高维空间中的距离累积效应导致点积方差线性增长

            # 数学原理：
            #   • 设 q_i, k_i ~ N(0,1) 独立同分布
            #   • Var(q·k) = Σ_i Var(q_i*k_i) = d_k * 1 = d_k
            #   • 标准差 = √d_k → 实际值域 ≈ ±3√d_k (99.7%置信区间)

